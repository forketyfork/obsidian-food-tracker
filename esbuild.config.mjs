import esbuild from "esbuild";
import { builtinModules } from "node:module";
import process from "node:process";
import fs from "node:fs";

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
If you want to view the source, please visit the GitHub repository of this plugin.
*/
`;

const prod = process.argv.includes("--production");
const watch = process.argv.includes("--watch");

const sharedOptions = {
	entryPoints: ["src/main.ts"],
	bundle: true,
	external: [
		"obsidian",
		"electron",
		"@codemirror/autocomplete",
		"@codemirror/collab",
		"@codemirror/commands",
		"@codemirror/language",
		"@codemirror/lint",
		"@codemirror/search",
		"@codemirror/state",
		"@codemirror/view",
		"@lezer/common",
		"@lezer/highlight",
		"@lezer/lr",
		...builtinModules,
	],
	format: "cjs",
	target: "es2018",
	logLevel: "info",
	sourcemap: prod ? false : "inline",
	treeShaking: true,
	outfile: "main.js",
	minify: prod,
	keepNames: true,
	banner: {
		js: banner,
	},
};

async function buildJS() {
	if (watch) {
		const context = await esbuild.context(sharedOptions);
		console.log("Watching for changes...");
		await context.watch();
	} else {
		await esbuild.build(sharedOptions);
	}
}

async function buildCSS() {
	const input = fs.readFileSync("src/styles.src.css", "utf-8");
	const result = await esbuild.transform(input, { loader: "css", minify: true });
	fs.writeFileSync("styles.css", result.code);
	console.log("Minified styles.css");
}

async function main() {
	if (prod) {
		await buildCSS();
	}
	await buildJS();
}

main().catch(err => {
	console.error(err);
	process.exit(1);
});
